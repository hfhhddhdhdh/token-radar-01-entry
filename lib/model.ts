// Token Radar — the value model (radar-2).
//
// One sealed snapshot in, one ranked board out. The board ranks every protocol
// that records no token and could plausibly issue one of its own: the snapshot's
// watchlist (40 protocols) plus every other pre-token protocol that passes the
// same exclusion test the house used for the watchlist — not a bridge, not a
// liquid-staking / restaking product, not a CEX, not a versioned pool, not a
// wrapped or staked product, not an exchange-branded product. Live-token
// protocols are never ranked: they are shown apart, with the market cap the
// market already gives them, and they double as the model's comparables.
//
// Implied value is derived from the snapshot's own figures, never from a
// hand-written list of names:
//
//   category multiple = median market-cap / TVL among live protocols in the
//                         same category, the median first clamped to
//                         [0.02, 2.0] (one live peer can carry an absurd
//                         ratio), then shrunk toward the global median
//                         (weight n / (n + 4)) and clamped to [0.02, 1.20].
//                         A category with few live peers therefore borrows
//                         most of its multiple from the whole market.
//   growth multiplier = 1 + clamp(change_7d, -60, 120) / 100 * 0.6
//   maturity          = 0.70 + min(age_days, 1095) / 1095 * 0.50
//                       (age unknown: 365 days — a protocol that has run a
//                       year with no token is proven, not brand new)
//   breadth           = 1 + 0.05 * min(chains - 1, 4)
//   implied           = round(tvl_usd * category multiple
//                             * growth * maturity * breadth)
//
// Why this shape: TVL is the size of the business a token would claim a share
// of; the category multiple is what the market actually pays per dollar of TVL
// for that kind of business (a DEX token is priced very differently from a
// lending token); seven-day growth separates protocols still compounding from
// ones shrinking; age with no token rewards a record that has survived time;
// chain breadth rewards reach across ecosystems. Every input is in the
// snapshot, so any reader can recompute any row — the dashboard does exactly
// that and shows whether its number matches board.json.

